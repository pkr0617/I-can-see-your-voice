from hangul import *

된소리 = {'ㄱ': 'ㄲ', 'ㄷ': 'ㄸ', 'ㅂ': 'ㅃ', 'ㅅ': 'ㅆ', 'ㅈ': 'ㅉ'}

#규칙으로는 안 되고 단어마다 정해진 된소리 (한자어·사이시옷): 단어 -> 된소리가 되는 글자 번호
#문법[문뻡]인데 방법[방법], 인기[인끼]인데 인간[인간]처럼 모양만으로는 구분이 안 됨 -> 틀리는 단어는 여기에 추가
#(물가, 잠자리처럼 뜻에 따라 발음이 다른 단어는 넣지 않음)
된소리_단어 = {
    '문법': 1, '헌법': 1, '한자': 1, '문자': 1, '인기': 1, '사건': 1, '조건': 1, '성격': 1,
    '쇠창살': 2, '그믐달': 2, '밤새': 1, '줄넘기': 2, '등불': 1, '손가락': 1, '눈동자': 1, '글자': 1,
}

#끝소리규칙보다 먼저 실행해야 함 (ㄺ,ㄼ,ㄾ 같은 겹받침 정보가 필요하기 때문)
def 경음화(음절들):
    for i in range(len(음절들) - 1):
        앞 = 음절들[i]
        뒤 = 음절들[i + 1]

        if 앞['한글아님'] is not None or 뒤['한글아님'] is not None:
            continue

        종 = 앞['종']
        초 = 뒤['초']
        if 종 == '' or 초 not in 된소리:
            continue

        #된소리_단어 사전에 있는 단어 (문법[문뻡], 그믐달[그믐딸])
        if 뒤['된소리예외']:
            뒤['초'] = 된소리[초]
            continue

        #제27항: 관형사형 어미 -(으)ㄹ 뒤 (어절 사이에도 적용: 할 것을[할껏을], 갈 데[갈떼])
        if 종 == 'ㄹ' and 앞['현재품사'].startswith('ETM'):
            뒤['초'] = 된소리[초]
            continue

        #제23항: 받침 ㄱ,ㄷ,ㅂ(으로 발음되는 받침) 뒤 ㄱ,ㄷ,ㅂ,ㅅ,ㅈ (국밥[국빱], 먹고[먹꼬], 옷도[옫또])
        #어절 사이: 한 글자 어절이나 의존명사 앞에서만 (못 잤어[몯짜써], 일곱 시[일곱씨] / 옆집 강아지, 알약 삼키다는 X)
        어절사이 = 앞['어절끝'] and 앞['어절음절수'] > 1 and 뒤['시작품사'] != 'NNB'
        if 대표음[종] in ('ㄱ', 'ㄷ', 'ㅂ') and not 어절사이 and not (앞['어절끝'] and 종 == 'ㄺ'):
            #제11항 다만: 용언 어간 ㄺ + ㄱ -> [ㄹ] + 된소리 (읽게[일께], 맑게[말께])
            if not 앞['어절끝'] and 앞['경계'] and 앞['다음품사'].startswith('E') and 종 == 'ㄺ' and 초 == 'ㄱ':
                앞['종'] = 'ㄹ'
            뒤['초'] = 된소리[초]
            continue

        if 앞['어절끝']:
            continue

        #제27항 붙임: 어미 -(으)ㄹ게, -(으)ㄹ지, -(으)ㄹ수록 안의 ㄹ 뒤 (할게[할께], 할지라도[할찌라도])
        if 종 == 'ㄹ' and 뒤['ㄹ어미']:
            뒤['초'] = 된소리[초]
            continue

        #제26항: 한자어 ㄹ 받침 뒤 ㄷ,ㅅ,ㅈ (갈등[갈뜽], 실수[실쑤], 열정[열쩡])
        #한 명사 안에서만 (kiwi로 한자어/고유어 구분은 안 됨: 발자국[발짜국]처럼 고유어 합성어도 대개 된소리)
        if 종 == 'ㄹ' and 초 in ('ㄷ', 'ㅅ', 'ㅈ') and 뒤['명사내부']:
            뒤['초'] = 된소리[초]
            continue

        #연음으로 옮겨온 소리는 받침 뒤가 아니므로 아래(24·25항) 적용 X (앉아[안자])
        if 뒤['연음됨']:
            continue

        #어간 + 어미의 경계에서만 쓰는 조건 (한다·먹는다처럼 받침이 어미 쪽에 있으면 제외)
        어간 = 앞['경계'] and 앞['다음품사'].startswith('E')

        #제25항: 어간 받침 ㄾ 뒤 ㄱ,ㄷ,ㅅ,ㅈ (핥다[할따], 훑소[훌쏘]) - ㄾ은 용언 어간에만 있어서 kiwi가 못 알아봐도 적용
        if 종 == 'ㄾ' and 초 in ('ㄱ', 'ㄷ', 'ㅅ', 'ㅈ'):
            뒤['초'] = 된소리[초]

        #제24항: 어간 받침 ㄴ(ㄵ),ㅁ(ㄻ) 뒤 어미 ㄱ,ㄷ,ㅅ,ㅈ (신고[신꼬], 앉고[안꼬], 삼고[삼꼬])
        #제25항: 어간 받침 ㄼ 뒤 어미 ㄱ,ㄷ,ㅅ,ㅈ (넓게[널께])
        elif 어간 and 종 in ('ㄴ', 'ㄵ', 'ㅁ', 'ㄻ', 'ㄼ') and 초 in ('ㄱ', 'ㄷ', 'ㅅ', 'ㅈ'):
            뒤['초'] = 된소리[초]

    #사이시옷 경음화, 개별 한자어 된소리는 형태소 정보만으로 구분이 안 되어 위 된소리_단어 사전으로만 처리
    return 음절들
