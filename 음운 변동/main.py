from kiwipiepy import Kiwi
from hangul import First, Second, Third, 겹받침
from 연음 import 연음
from 구개음화 import 구개음화
from 모음규칙 import 모음규칙
from 유음화 import 유음화
from 비음화 import 비음화 
from 니은첨가 import 니은첨가
from 히읗규칙 import 히읗규칙
from 경음화 import 경음화
from 끝소리규칙 import 끝소리규칙, 밟다예외
from 모음규칙 import 져쪄쳐
from 경음화 import 된소리_단어
from 복합어 import 경계찾기

kiwi = Kiwi()

문장= input() + ' '

def inputed_sentence():
    return 문장[:-1]

형태소=kiwi.tokenize(문장) #나중에 음운변동처리할때 쓸꺼임
형태소_정보={}
시작위치={t.start for t in 형태소}   # 형태소가 시작하는 글자 위치들 (뒤 음절이 새 형태소의 시작인지 판단용)
for i in range(len(형태소)):
    현재 = 형태소[i]
    끝위치= 현재.start+현재.len-1
    if i+1<len(형태소):
        다음품사=형태소[i+1].tag
        다음형태=형태소[i+1].form
    else:
        다음품사=''
        다음형태=''
    다음형식=다음품사.startswith('J') or 다음품사.startswith('E') or 다음품사.startswith('XS') or 다음품사=='VCP'
    if 다음품사=='XSN' and 다음형태 in ('용', '율'):   # 영업용[영엄뇽], 백분율[백뿐뉼]: 접미사지만 ㄴ첨가됨
        다음형식=False
    형태소_정보[끝위치]= {'형태소끝':True, '다음형식':다음형식, '다음품사':다음품사, '현재품사':현재.tag, '경계':(끝위치+1) in 시작위치}

#글자 위치별 추가 정보
추가={}   # 위치 -> {이름: 값}
def 표시(위치, 이름, 값=True):
    추가.setdefault(위치, {})[이름] = 값

for 현재 in reversed(형태소):     # 같은 위치에서 시작하는 형태소가 여러 개면 맨 앞 것이 남도록 거꾸로
    표시(현재.start, '시작품사', 현재.tag)
    표시(현재.start, '시작길이', 현재.len)

for 현재 in 형태소:
    겉모양 = 문장[현재.start:현재.start+현재.len]
    #-(으)ㄹ게, -(으)ㄹ지, -(으)ㄹ수록 등: 어미 안의 ㄹ 뒤 된소리 (제27항 붙임: 할게[할께])
    if 현재.tag.startswith('E') and 현재.form[:1] in ('ᆯ', '을') and 현재.len >= 2:
        표시(현재.start+1, 'ㄹ어미')
    #붙여[부처], 굳혀: kiwi가 '붙이+어'를 '붙이' 하나가 두 글자(붙,여)를 차지하는 식으로 줌
    if 현재.tag.startswith('V') and 현재.form[-1:] in ('이', '히') and 현재.len >= 2 and 겉모양[-1] not in ('이', '히'):
        표시(현재.start+현재.len-1, '이어줄임')
    if 현재.tag.startswith('VA') and 겉모양 == 현재.form:
        for j, 종류 in 경계찾기(현재.form):     # 맛없다[마덥따]
            형태소_정보[현재.start+j-1] = {'형태소끝':True, '다음형식':False, '다음품사':현재.tag, '현재품사':'NNG', '경계':True}
    #문법[문뻡], 한자[한짜]: 규칙으로 안 되는 된소리는 경음화.py의 된소리_단어 사전으로
    if 현재.form in 된소리_단어 and 겉모양 == 현재.form:
        표시(현재.start+된소리_단어[현재.form], '된소리예외')
    if 현재.tag in ('NNG', 'NNP'):
        for k in range(1, 현재.len):
            표시(현재.start+k, '명사내부')   # 한자어 ㄹ 뒤 된소리용 (갈등[갈뜽], 실수[실쑤])
        #생산량[생산냥], 공권력[공꿘녁]: 'ㄴ+ㄹ'인데 ㄹ이 접미사 같은 한자 (제20항 붙임)
        if 현재.tag == 'NNG' and 현재.len >= 3 and 겉모양[-1] in ('란', '량', '력', '령', '례', '로', '론', '료', '류'):
            표시(현재.start+현재.len-1, 'ㄹ접미')
        #kiwi가 한 덩어리로 준 합성어 안의 경계 (솜이불, 늑막염, 겉옷)
        if 겉모양 == 현재.form:
            for j, 종류 in 경계찾기(현재.form):
                위치 = 현재.start + j
                형태소_정보[위치-1] = {'형태소끝':True, '다음형식':False, '다음품사':'NNG', '현재품사':현재.tag, '경계':True}
                if 종류 == '15항':
                    표시(위치, '첨가없음')


음절들 =[]

for i in range(len(문장)): #안녕 하세요면 문장[0]='안', 문장[1]='녕', 문장[2]=' ', 문장[3]='하', 문장[4]='세', 문장[5]='요'
    char=문장[i]
    음절 = {'초':'', '중':'', '종':'', '어절끝':False, '한글아님': None}

    if char==' ':
        if len(음절들)>0:
            음절들[-1]['어절끝'] = True
        continue

        #어캐 나누냐 -> ord라는 함수가 있는데 이게 유니코드값을 가져오는
        #유니코드 한글은 0xAC00 으로부터 
        #초성 19개, 중성21개, 종성28개로 이루어지고
	    #이들을 조합한 11,172개의 문자를 갖는다.
    	#한글코드의 값 = ((초성 * 21) + 중성) * 28 + 종성 + 0xAC00
	    #(0xAC00은 '가'의 코드값)

	    #따라서 다음과 같은 계산 식이 구해진다.
	    #유니코드 한글 문자 코드 값이 X일 때,

	    #초성 = ((X - 0xAC00) // 28) // 21
	    #중성 = ((X - 0xAC00) // 28) % 21
	    #종성 = (X - 0xAC00) % 28
        #https://github.com/neotune/python-korean-handler/blob/master/korean_handler.py

    초중성_uni_code = ord(char) - 0xAC00

    if 0 <= 초중성_uni_code < 11172:
        음절['초'] = First[초중성_uni_code // (21 * 28)] #한 초성의 경우의 수는 중성 21x종성 28임
        음절['중'] = Second[(초중성_uni_code // 28) % 21]
        음절['종'] = Third[초중성_uni_code % 28]
    else:
        음절['한글아님'] = char

    정보 = 형태소_정보.get(i, {'형태소끝': False, '다음형식': False, '다음품사': '', '현재품사': '', '경계': False}) #i가 있으면 꺼내고 아니면 중괄호 안에 있는 정보
    음절['형태소끝'] = 정보['형태소끝']
    음절['다음형식'] = 정보['다음형식']
    음절['다음품사'] = 정보['다음품사']
    음절['현재품사'] = 정보['현재품사']
    음절['경계'] = 정보['경계']
    음절['시작품사'] = ''
    음절['시작길이'] = 0
    for 이름 in ('ㄹ어미', '명사내부', 'ㄹ접미', '첨가없음', '연음됨', '첨가', '이어줄임', '된소리예외'):
        음절[이름] = False
    음절.update(추가.get(i, {}))
    음절들.append(음절)

#어절 음절 수 (한 글자짜리 어절은 뒤 어절에 붙여 발음: 밥 먹고[밤먹꼬], 몇 년[면년])
시작 = 0
for k in range(len(음절들)):
    if 음절들[k]['어절끝'] or k == len(음절들)-1:
        for m in range(시작, k+1):
            음절들[m]['어절음절수'] = k+1-시작
        시작 = k+1

#규칙 입력
음절들=모음규칙(음절들)   # 의/예/례 등 모음 발음을 먼저 정해 둠 (닭의 -> 닭에 -> 달게)
음절들=구개음화(음절들)   # 연음보다 먼저 (연음이 받침을 옮기고 나면 구개음화 조건이 사라짐)
음절들=연음(음절들)
음절들=니은첨가(음절들)  # 연음 뒤, 비음화/유음화 앞 (옷 입다 -> 온닙따, 솔잎 -> 솔립)
음절들=밟다예외(음절들)  # 밟-[밥], 넓죽하다[넙쭈카다] (히읗규칙 앞: 넓죽하다의 '죽'이 '주'로 바뀌기 전에)
음절들=히읗규칙(음절들)  # 격음화 등 (끝소리규칙보다 먼저: ㅎ·겹받침 정보가 필요)
음절들=경음화(음절들)    # 끝소리규칙보다 먼저: ㄺ,ㄼ,ㄾ 어간 정보가 필요
음절들=끝소리규칙(음절들) # 남은 받침을 대표음으로
음절들=비음화(음절들)
음절들=유음화(음절들)
음절들=져쪄쳐(음절들)    # 맨 마지막: 구개음화로 생긴 '쳐'도 바꿔야 함 (붙여[부처])


for i in 음절들:
    print(i['초'], i['중'], i['종'], i['어절끝'], i['한글아님'])
