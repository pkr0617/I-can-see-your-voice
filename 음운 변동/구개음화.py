from hangul import *

def 구개음화(음절들):
    for i in range(len(음절들)-1):
        앞=음절들[i]
        뒤=음절들[i+1]

        if 앞['한글아님'] is not None or 뒤['한글아님'] is not None:
            continue
        if 앞['어절끝'] is True:
            continue

        #뒤가 새 실질 형태소면 구개음화 X (밭이랑[반니랑], 홑이불[혼니불]: ㄴ첨가 쪽으로 감)
        #그 외(조사·접사 '이'가 붙거나 kiwi가 한 단어로 준 굳이, 같이, 해돋이, 붙이다)는 구개음화
        if 앞['형태소끝'] and not 앞['다음형식']:
            continue

        #붙여[부처], 굳혀: 이+어가 줄어든 '여'도 구개음화
        if 뒤['초']=='ㅇ' and 뒤['중']=='ㅕ' and 뒤['이어줄임'] and 앞['종'] in ('ㄷ', 'ㅌ'):
            뒤['초'] = 'ㅈ' if 앞['종']=='ㄷ' else 'ㅊ'
            앞['종'] = ''

        #제17항구개음화
        if 뒤['초']=='ㅇ' and 뒤['중']=='ㅣ' :

            if 앞['종']=='ㄷ' :
                앞['종']=''
                뒤['초']='ㅈ'

            elif 앞['종']=='ㅌ' :
                앞['종']=''
                뒤['초']='ㅊ'

            elif 앞['종']=='ㄾ' :     # 핥이다[할치다]
                앞['종']='ㄹ'
                뒤['초']='ㅊ'

    return 음절들
