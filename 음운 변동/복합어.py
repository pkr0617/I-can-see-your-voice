#kiwi가 한 덩어리(NNG)로 주는 합성어 안에서 형태소 경계를 찾아줌
#(솜이불, 늑막염, 겉옷처럼 경계가 있어야 ㄴ첨가·15항 연음이 됨)
#kiwi는 모르는 말도 NNG로 추측해서 조각만으로는 명사인지 믿을 수 없음 -> 뒷말 목록으로 판단
#새 단어가 틀리면 아래 목록에 추가하면 됨

#앞말이 무엇이든 ㄴ첨가 되는 뒷말 (솜이불, 밭이랑, 한여름, 색연필, 눈요기, 꽃잎, 물엿, 밤윷)
ㄴ첨가_뒷말 = {'이불', '이랑', '이슬', '여름', '연필', '요기', '윤리', '열차', '여성', '이야기', '잎', '엿', '윷'}

#한자 한 글자 뒷말: 앞말이 2음절 이상일 때만 (내복약, 서울역, 늑막염, 식용유 / 독약·절약·석유는 X)
ㄴ첨가_한자뒷말 = {'약', '역', '염', '유', '율', '용'}

#두 글자 단어라 위 규칙으로 못 잡는 것들: 단어 -> 경계 위치(뒷말이 시작하는 글자 번호)
ㄴ첨가_단어 = {'담요': 1, '알약': 1, '물약': 1, '눈약': 1, '밭일': 1, '앞일': 1, '막일': 1,
            '들일': 1, '삯일': 1, '맨입': 1, '논일': 1}

#ㄴ첨가 없이 대표음으로 바꿔서 연음 (제15항: 겉옷[거돋], 낱알[나ː달], 값어치[가버치], 첫인상[처딘상])
연음_뒷말 = {'옷', '알', '웃음', '어치', '인상', '없'}   # 맛없다[마덥따]


def 경계찾기(형태):
    """합성어 형태(문자열)를 받아 [(뒷말 시작 위치, 'ㄴ첨가' 또는 '15항'), ...]을 돌려줌"""
    결과 = []
    if 형태 in ㄴ첨가_단어:
        return [(ㄴ첨가_단어[형태], 'ㄴ첨가')]
    for j in range(1, len(형태)):
        뒷말 = 형태[j:]
        if 뒷말 in 연음_뒷말:
            결과.append((j, '15항'))
        elif 뒷말 in ㄴ첨가_뒷말:
            결과.append((j, 'ㄴ첨가'))
        elif 뒷말 in ㄴ첨가_한자뒷말 and j >= 2:
            결과.append((j, 'ㄴ첨가'))
        if 결과:
            break
    return 결과
