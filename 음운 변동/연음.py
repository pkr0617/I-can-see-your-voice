from hangul import *
from 니은첨가 import 니은첨가대상

제15항모음 = ['ㅏ', 'ㅓ', 'ㅗ', 'ㅜ', 'ㅟ']

def 대표음연음(앞, 뒤):
    """제15항: 받침을 대표음으로 바꾼 뒤 옮김. 겹받침도 대표음 하나만 (넋 없다[너겁따], 닭 앞에[다가페])"""
    뒤['초'] = 대표음[앞['종']]
    앞['종'] = ''
    뒤['연음됨'] = True


def 연음(음절들):
    for i in range(len(음절들) - 1):
        앞=음절들[i]
        뒤=음절들[i + 1]

        if 앞['한글아님'] is not None or 뒤['한글아님'] is not None:
            continue
        if 앞['종']=='' or 앞['종']=='ㅇ' or 뒤['초']!= 'ㅇ':
            continue

        #어절 사이: 이어서 발음할 때만 (꽃 위에[꼬뒤에], 못 이겨서[모디겨서])
        #받침이 대표음 그대로인 것(ㄱ,ㄴ,ㄹ,ㅁ,ㅂ...)은 띄어 읽음 (하늘 아래, 동안 아이는, 서울역 앞)
        if 앞['어절끝']:
            if 니은첨가대상(앞, 뒤):        # 먹는 약[멍는냑]은 ㄴ첨가(니은첨가.py)가 처리
                continue
            if 앞['종'] == 'ㅎ' or 대표음[앞['종']] == 앞['종']:
                continue
            대표음연음(앞, 뒤)
            continue

        #15항: 뒤가 실질 형태소 (겉옷[거돋], 밭 아래, 맛없다[마덥따])
        if 앞['형태소끝'] and not 앞['다음형식']:
            if 니은첨가대상(앞, 뒤):
                continue   # 솜이불 같은 경우는 연음이 아니라 ㄴ첨가(니은첨가.py)가 처리
            if 뒤['중'] in 제15항모음 or 뒤['첨가없음']:
                대표음연음(앞, 뒤)
                continue

        #13,14항
        #기본 (조사·어미·접미사 앞)
        뒤['연음됨'] = True
        if 앞['종'] == 'ㅎ':
            앞['종'] = ''
            뒤['초'] = 'ㅇ'
        elif 앞['종'] in ('ㄶ', 'ㅀ'):
            뒤['초'] = 겹받침[앞['종']][0]
            앞['종'] = ''
        elif 앞['종'] in 겹받침:
            뒤['초'] = 겹받침[앞['종']][1]
            앞['종'] = 겹받침[앞['종']][0]
        else:
            뒤['초'] = 앞['종'] #위아래 줄 바꾸면 큰일난디...
            앞['종'] = ''


    return 음절들
