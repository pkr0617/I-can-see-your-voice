from hangul import *

def  유음화(음절들):
    for i in range(len(음절들) - 1):
        앞=음절들[i]
        뒤=음절들[i + 1]

        if 앞['한글아님'] is not None or 뒤['한글아님'] is not None:
            continue

        #한자어 구분하여 한자어일떄는 작동 안한다는 내용
        #한자어 부분 제외 -> 생산량[생산냥] 같은 것만 'ㄹ접미' 표시로 처리

        #순행동화 (ㄹ+ㄴ): 어절 안에서만. 어절 사이는 ㄴ첨가로 생긴 ㄴ일 때만 (할 일[할릴])
        #몫을 나누다[목쓸 나누다], 넋을 놓고[넉쓸 노코]
        if 앞['종']=='ㄹ' and 뒤['초']=='ㄴ':
            if not 앞['어절끝'] or 뒤['첨가']:
                뒤['초']='ㄹ'

        #역행동화 (ㄴ+ㄹ): 어절 사이에도 적용 (천 리[철리])
        elif 앞['종']=='ㄴ' and 뒤['초']=='ㄹ':
            if 뒤['ㄹ접미'] and not 앞['어절끝']:
                뒤['초']='ㄴ'     # 제20항 붙임: 생산량[생산냥], 의견란[의ː견난]
            else:
                앞['종']='ㄹ'

    #미완
    #끝소리 규칙 필요
    return 음절들
